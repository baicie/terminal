// Get theme colors by preset
export function getThemeColors(
  preset: TerminalThemePreset,
): TerminalThemeColors {
  return terminalThemes[preset] || terminalThemes['one-dark']
}

// Convert theme to xterm options
export function themeToXtermOptions(preset: TerminalThemePreset) {
  const colors = getThemeColors(preset)
  return {
    theme: colors,
  }
}
