-- Phase 9.0 P9.0-2 — 同步作用域：成员加入水位（joinedTxid）
-- 前向兼容：只新增一列并给默认值，不删列、不改类型、不改既有约束。
-- 旧二进制继续读写 TeamMember：它不认识该列，由数据库默认值维护。
--
-- 作用：同步窗口的作用域是「该用户当前的完整成员集合」。游标只能在这个作用域
-- 内作为位置使用；若某个成员是在游标位置之后才加入的，那么该团队的既有共享
-- 从未落在窗口里（它们的 txid 早于游标），继续沿用游标就会永久跳过这支历史。
-- 因此服务端在每次请求时比较 joinedTxid 与游标位置，一旦有成员更晚加入就退回
-- 全量重同步（resync），绝不猜测（docs/phase8/sync-protocol.md §3.8）。
--
-- 用事务号而不是 joinedAt 的原因：本协议的所有位置判定都基于 xid8，不依赖任何
-- 时钟；时钟无法判定「加入」与「提交」的先后（见 sync-protocol.md §3.2）。
--
-- 回填语义：ADD COLUMN + 易变默认值会让既有行取到本次迁移事务的事务号。
-- 它是「比任何既有游标都新」的值，所以每个客户端在迁移后的第一次同步都会做一次
-- 全量重同步，此后游标位置越过它即恢复增量。这一步是刻意的：迁移前「加入团队
-- 后被旧游标跳过」的历史缺口无法在服务端复原，一次全量重同步是唯一能把它补上的
-- 手段（协议 1 的数字游标同样适用，因为它走的是同一段作用域判定）。

ALTER TABLE "TeamMember"
    ADD COLUMN "joinedTxid" BIGINT NOT NULL
    DEFAULT pg_current_xact_id()::text::bigint;

-- 读取路径按 userId 取全部成员关系，再比较 joinedTxid；成员集合规模是「人 × 团队」，
-- 不需要额外索引。

-- ---------------------------------------------------------------------------
-- DOWN MIGRATION（回退方案）
--
--   ALTER TABLE "TeamMember" DROP COLUMN IF EXISTS "joinedTxid";
--
-- 回退后的影响：服务端退回到「游标只按 safe 水位校验」的旧语义，于是新加入团队
-- 的历史又会被旧游标跳过（即本迁移要修的那个缺陷）。回退不需要停写：该列只被
-- 读路径使用，没有触发器、没有变更日志、不影响 Share 的版本语义。
-- 已按新语义做过一次全量重同步的客户端会保留新的游标，回退后行为与旧版本一致。
